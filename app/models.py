from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field


class UploadDatabaseResponse(BaseModel):
    db_id: str
    name: str
    tables: list[str]


class ConnectDatabaseRequest(BaseModel):
    name: str = Field(..., min_length=1, description="Friendly connection name")
    db_url: str = Field(..., min_length=8, description="SQLAlchemy database URL")


class ConnectDatabaseResponse(BaseModel):
    db_id: str
    name: str
    tables: list[str]


class QueryRequest(BaseModel):
    db_id: str = Field(..., description="Database identifier returned by upload")
    question: str = Field(..., min_length=3, description="Natural language question")
    max_rows: int = Field(default=1000, ge=1, le=10000)


class ValidationIssue(BaseModel):
    level: str
    message: str


class QueryMetrics(BaseModel):
    generation_ms: float
    validation_ms: float
    execution_ms: float
    total_ms: float
    attempts: int


class QueryResponse(BaseModel):
    db_id: str
    question: str
    sql: str
    valid: bool = False
    executed: bool = False
    columns: list[str]
    rows: list[list[Any]]
    row_count: int
    truncated: bool
    model_used: str | None = None
    issues: list[str] = Field(default_factory=list)
    metrics: QueryMetrics
    validation_issues: list[ValidationIssue] = Field(default_factory=list)
    # Show what each model generates for debugging
    model_outputs: dict[str, str] = Field(default_factory=dict, description="SQL generated by each model (flan_t5, mistral_7b)")


class ModelQueryResult(BaseModel):
    model_name: str
    available: bool
    sql: str
    valid: bool
    executed: bool
    attempts: int
    columns: list[str] = Field(default_factory=list)
    rows: list[list[Any]] = Field(default_factory=list)
    issues: list[str] = Field(default_factory=list)
    row_count: int = 0
    truncated: bool = False
    metrics: QueryMetrics
    validation_issues: list[ValidationIssue] = Field(default_factory=list)
    error: str | None = None
    # Optional generation trace: raw Decoded, extracted, postprocessed
    trace: dict | None = None


class CompareQueryResponse(BaseModel):
    db_id: str
    question: str
    winner_model: str | None
    winner_reason: str
    models: dict[str, ModelQueryResult]
